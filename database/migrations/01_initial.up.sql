-- ============================================================
-- Table: kassenjournal (Event Store for all kasse operations)
-- ============================================================
-- Append-only, never updated or deleted (INSERT and SELECT only).
CREATE TABLE kassenjournal (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT REFERENCES users(id) NOT NULL,
    user_name TEXT NOT NULL,
    type TEXT NOT NULL,
    subject TEXT NOT NULL,
    version INT NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL,
    data JSONB NOT NULL,
    kassensitzung_nr INT NOT NULL REFERENCES kassensitzungen(z_nr),
    UNIQUE (subject, version)
);

CREATE INDEX idx_kassenjournal_user_id ON kassenjournal(user_id);
CREATE INDEX idx_kassenjournal_subject_type ON kassenjournal(subject, type);
CREATE INDEX idx_kassenjournal_type_timestamp ON kassenjournal(type, timestamp);
CREATE INDEX idx_kassenjournal_ks_nr ON kassenjournal(kassensitzung_nr);

-- Restrict public role to SELECT + INSERT only (defense-in-depth for non-owner roles)
REVOKE ALL ON TABLE kassenjournal FROM PUBLIC;
GRANT SELECT, INSERT ON TABLE kassenjournal TO PUBLIC;

-- Triggers to enforce append-only immutability for ALL roles, including the table owner.
-- REVOKE/GRANT alone is not sufficient because PostgreSQL table owners bypass privilege checks.
-- Generic write-protection guard, shared with the insert-once kassenidentitaet table.
CREATE OR REPLACE FUNCTION prevent_table_mutation() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'table % is write-protected: % not allowed', TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER kassenjournal_no_update
    BEFORE UPDATE ON kassenjournal FOR EACH ROW
    EXECUTE FUNCTION prevent_table_mutation();

CREATE TRIGGER kassenjournal_no_delete
    BEFORE DELETE ON kassenjournal FOR EACH ROW
    EXECUTE FUNCTION prevent_table_mutation();

CREATE TRIGGER kassenjournal_no_truncate
    BEFORE TRUNCATE ON kassenjournal FOR EACH STATEMENT
    EXECUTE FUNCTION prevent_table_mutation();

COMMENT ON TABLE kassenjournal IS 'Append-only Kassenjournal (Event Store) for all kasse operations (event-sourcing)';
COMMENT ON COLUMN kassenjournal.user_id IS 'Actor who triggered the event';
COMMENT ON COLUMN kassenjournal.user_name IS 'Display name of the actor at the time of the event';
COMMENT ON COLUMN kassenjournal.version IS 'Optimistic concurrency version per subject (monotonically increasing)';
COMMENT ON COLUMN kassenjournal.type IS 'Event type identifier, e.g., bestellung-aufgenommen:v1';
COMMENT ON COLUMN kassenjournal.subject IS 'Aggregate key, e.g. "kassensitzung-1/tisch-42" for a tisch session, "kassensitzung-1" for a kassensitzung';
COMMENT ON COLUMN kassenjournal.timestamp IS 'Event time (UTC)';
COMMENT ON COLUMN kassenjournal.data IS 'Event data (jsonb), versioned by type';
COMMENT ON COLUMN kassenjournal.kassensitzung_nr IS 'Kassensitzung number (z_nr) this event belongs to';

