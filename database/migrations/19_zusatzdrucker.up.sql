-- Zusatzdrucker: benannte Drucker neben den Druckstationen der Kategorien.
-- Ein zugeordnetes Produkt druckt seinen Arbeitsbon dort statt an der
-- Druckstation seiner Kategorie.
--
-- Additiv: zwei neue, leere Tabellen; druckstationen bleibt unberührt.
BEGIN;

CREATE TABLE zusatzdrucker (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    drucker_ip  TEXT NOT NULL,
    bonmodus    TEXT NOT NULL CHECK (bonmodus IN ('pro_position', 'pro_bestellung')),
    updated_at  TIMESTAMPTZ NOT NULL
);

COMMENT ON TABLE zusatzdrucker IS 'Benannter Drucker für einzeln zugeordnete Produkte; Konfiguration wie druckstationen, hart gelöscht.';
COMMENT ON COLUMN zusatzdrucker.name IS 'Anzeigename, steht auch auf dem Testbon (3 bis 100 Zeichen, geprüft im Backend).';
COMMENT ON COLUMN zusatzdrucker.drucker_ip IS 'IPv4-Adresse des Bondruckers (leer = kein Drucker konfiguriert)';
COMMENT ON COLUMN zusatzdrucker.bonmodus IS 'Bonmodus: pro_position (1 Bon pro Position) oder pro_bestellung (1 Sammelbon).';

CREATE TABLE zusatzdrucker_produkte (
    produkt_id        INT PRIMARY KEY REFERENCES produkte(id) ON DELETE CASCADE,
    zusatzdrucker_id  INT NOT NULL REFERENCES zusatzdrucker(id) ON DELETE CASCADE
);

CREATE INDEX idx_zusatzdrucker_produkte_zusatzdrucker_id ON zusatzdrucker_produkte (zusatzdrucker_id);

COMMENT ON TABLE zusatzdrucker_produkte IS 'Zuordnung Produkt → Zusatzdrucker; höchstens ein Zusatzdrucker je Produkt.';
COMMENT ON COLUMN zusatzdrucker_produkte.produkt_id IS 'Zugeordnetes Produkt; sein Arbeitsbon druckt am Zusatzdrucker statt an der Druckstation seiner Kategorie.';
COMMENT ON COLUMN zusatzdrucker_produkte.zusatzdrucker_id IS 'Zusatzdrucker des Produkts; Löschen des Zusatzdruckers entfernt die Zuordnung.';

COMMIT;
